import { readFile, writeFile, mkdir, rename, rm } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'

const modules = ['plugin.js', 'inbox-observer-runtime.js', 'inbox-query.js', 'inbox-open-gesture.js', 'inbox-open-intent.js', 'inbox-row-ui.js', 'inbox-runtime.js']
const source = (await Promise.all(modules.map(file => readFile(new URL('../src/' + file, import.meta.url), 'utf8')))).join('\n\n')
const license = (await readFile(new URL('../LICENSE', import.meta.url), 'utf8')).trim()
const output = '// Generated by scripts/build.mjs. Edit src/ instead.\n/*\n' + license + '\n*/\n' + source
const check = spawnSync(process.execPath, ['--check', '--input-type=module'], { input: output, encoding: 'utf8' })
if (check.status !== 0) throw Error(check.stderr || 'Plugin syntax check failed')
const digest = createHash('sha256').update(output).digest('hex')
const target = new URL('../hermes-dynamic-sidebar/plugin.js', import.meta.url)
await mkdir(new URL('.', target), { recursive: true })
const temporary = new URL(`plugin.js.build-${process.pid}`, target)
try {
  await writeFile(temporary, output)
  await rename(temporary, target)
} finally { await rm(temporary, { force: true }) }
await writeFile(new URL('../CHECKSUMS.sha256', import.meta.url), `${digest}  hermes-dynamic-sidebar/plugin.js\n`)
console.log(JSON.stringify({ digest, bytes: Buffer.byteLength(output) }))
